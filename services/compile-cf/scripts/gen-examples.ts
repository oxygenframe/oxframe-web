// Bundles the site's example sources into the Worker (src/examples.gen.ts),
// so /api/examples and the prebuild cron know them without a container.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dir = join(import.meta.dir, '../../../apps/site/src/lib/examples');
const examples = readdirSync(dir)
  .filter((f) => f.endsWith('.rs'))
  .sort()
  .map((f) => {
    const source = readFileSync(join(dir, f), 'utf8');
    return {
      name: f.replace(/\.rs$/, ''),
      title: /^\/\/!\s*(.+)$/m.exec(source)?.[1] ?? f,
      source,
    };
  });
writeFileSync(
  join(import.meta.dir, '../src/examples.gen.ts'),
  `// Generated by scripts/gen-examples.ts; do not edit.\nimport type { Example } from './service';\n\nexport const examples: Example[] = ${JSON.stringify(examples, null, 2)};\n`,
);
console.log(`bundled ${examples.length} examples`);
