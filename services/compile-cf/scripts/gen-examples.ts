// Generates src/examples.gen.ts for the Worker:
// - the site's example sources, so /api/examples and the prebuild cron know
//   them without waking a container;
// - BUILD_ID, a hash of everything the container image is built from. It is
//   part of every cache key and passed to the container, so a new image never
//   reuses old artifacts and an unchanged one keeps them, however it is
//   deployed (Workers Builds or by hand).
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const root = join(import.meta.dir, '../../..');
const exDir = join(root, 'apps/site/src/lib/examples');
const examples = readdirSync(exDir)
  .filter((f) => f.endsWith('.rs'))
  .sort()
  .map((f) => {
    const source = readFileSync(join(exDir, f), 'utf8');
    return {
      name: f.replace(/\.rs$/, ''),
      title: /^\/\/!\s*(.+)$/m.exec(source)?.[1] ?? f,
      source,
    };
  });

const SDK_VERSION = '0.1.0';
const imageInputs = [
  'services/compile-cf/Dockerfile',
  'services/compile-cf/container',
  'services/compile/package.json',
  'services/compile/src',
  'infra/sandbox/template',
];
const files = (p: string): string[] =>
  statSync(p).isDirectory()
    ? readdirSync(p)
        .sort()
        .flatMap((e) => files(join(p, e)))
    : [p];
const hash = createHash('sha256').update(SDK_VERSION);
for (const f of imageInputs.flatMap((p) => files(join(root, p)))) {
  hash.update(`\0${relative(root, f)}\0`).update(readFileSync(f));
}
const buildId = `${SDK_VERSION}-${hash.digest('hex').slice(0, 12)}`;

writeFileSync(
  join(import.meta.dir, '../src/examples.gen.ts'),
  `// Generated by scripts/gen-examples.ts; do not edit.\nimport type { Example } from './service';\n\nexport const SDK_VERSION = ${JSON.stringify(SDK_VERSION)};\nexport const BUILD_ID = ${JSON.stringify(buildId)};\n\nexport const examples: Example[] = ${JSON.stringify(examples, null, 2)};\n`,
);
console.log(`bundled ${examples.length} examples, build id ${buildId}`);
