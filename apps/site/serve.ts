// Static server for the built site with security headers. CSP: no
// 'unsafe-eval' anywhere; 'wasm-unsafe-eval' is added only for the two
// worker scripts that compile wasm: the engine (with the compile origin) and
// the docs search.
import { existsSync, statSync } from 'node:fs';
import { join, normalize } from 'node:path';
import { compileUrl } from './compile-url.js';
import { redirectFor } from './redirects';

// SITE_DIR: the built site when this server runs as a compiled binary.
const root = process.env.SITE_DIR ?? join(import.meta.dir, 'build');
const compile = compileUrl();
const port = Number(process.env.PORT ?? 3000);

// Pages carry their CSP in a <meta> tag generated by SvelteKit (with hashes
// for its inline scripts); the header adds only what meta cannot express.
const pageCsp = `frame-ancestors 'self'; object-src 'none'; base-uri 'self'`;
const workerCsp = `default-src 'self'; connect-src 'self' ${compile}; script-src 'self' ${compile} 'wasm-unsafe-eval'`;
// The docs search worker runs Pagefind, which is wasm too.
const searchCsp = `default-src 'self'; script-src 'self' 'wasm-unsafe-eval'`;

Bun.serve({
  port,
  async fetch(req) {
    const url = new URL(req.url);
    const redirect = redirectFor(url.pathname);
    if (redirect) return Response.redirect(new URL(redirect.to, url), redirect.status);
    let path = normalize(decodeURIComponent(url.pathname)).replace(/^(\.\.[/\\])+/, '');
    let file = join(root, path);
    // adapter-static writes /docs as docs.html next to the docs/ directory.
    if (existsSync(`${file}.html`)) file = `${file}.html`;
    else if (existsSync(file) && statSync(file).isDirectory()) file = join(file, 'index.html');
    if (!file.startsWith(root) || !existsSync(file)) {
      file = join(root, '404.html');
      path = '/404';
    }
    const headers: Record<string, string> = {
      'X-Content-Type-Options': 'nosniff',
      'Referrer-Policy': 'strict-origin-when-cross-origin',
      'Content-Security-Policy': /engine-worker|^\/player-worker\.js$/.test(path)
        ? workerCsp
        : /search-worker/.test(path)
          ? searchCsp
          : pageCsp,
    };
    // <oxframe-player> is embedded on other sites.
    if (path === '/player.js' || path === '/player-worker.js') {
      headers['Access-Control-Allow-Origin'] = '*';
      headers['Cache-Control'] = 'public, max-age=3600';
    }
    if (path.includes('/_app/immutable/'))
      headers['Cache-Control'] = 'public, max-age=31536000, immutable';
    return new Response(Bun.file(file), { headers });
  },
});
console.log(`site on http://127.0.0.1:${port}`);
