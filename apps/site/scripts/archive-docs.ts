// Archives the current docs as a version snapshot. Run it when a new minor
// version is released, before the docs change for that version:
//
//   bun scripts/archive-docs.ts 0.1
//
// Copies every page under src/routes/docs into src/routes/docs/0.1/ (links
// rewritten to stay inside the snapshot; playground links carry `v=0.1`)
// and the page list into src/lib/docs-archive/0.1.ts. The docs layout,
// version switcher and sitemap pick the snapshot up from there.
import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';

export interface ArchiveOptions {
  series: string;
  /** src/routes/docs */
  routesDir: string;
  /** src/lib/docs-archive */
  archiveDir: string;
  /** The current page list (src/lib/docs.ts `sections`). */
  sections: unknown;
}

/** A docs key: a minor series (`0.1`) or an exact version (`0.2.1`). */
const isSeries = (name: string) => /^\d+\.\d+(\.\d+)?$/.test(name);

/** Points links of a copied page at the snapshot. */
export function rewriteLinks(source: string, series: string): string {
  return source
    .replace(
      /(["'`(])\/docs(?=[/"'`#)?])(?!\/\d+\.\d+(?:\.\d+)?(?:[/"'`#)?]))/g,
      `$1/docs/${series}`,
    )
    .replace(/\/playground\?ex=/g, `/playground?v=${series}&ex=`);
}

function pageFiles(dir: string, root: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    if (statSync(path).isDirectory())
      // Older snapshots are not part of the current docs.
      return dir === root && isSeries(name) ? [] : pageFiles(path, root);
    // The layout is shared by all versions.
    return /^\+page(\.server)?\.(svelte|ts)$/.test(name) ? [path] : [];
  });
}

export function archiveDocs({ series, routesDir, archiveDir, sections }: ArchiveOptions): string[] {
  if (!isSeries(series)) throw new Error(`expected a version like 0.1 or 0.2.1, got ${series}`);
  const target = join(routesDir, series);
  if (existsSync(target)) throw new Error(`${target} exists: ${series} is already archived`);
  const written: string[] = [];
  for (const file of pageFiles(routesDir, routesDir)) {
    const out = join(target, relative(routesDir, file));
    mkdirSync(dirname(out), { recursive: true });
    writeFileSync(out, rewriteLinks(readFileSync(file, 'utf8'), series));
    written.push(out);
  }
  mkdirSync(archiveDir, { recursive: true });
  const list = join(archiveDir, `${series}.ts`);
  writeFileSync(
    list,
    `// Page list of the oxframe ${series} docs (snapshot, see scripts/archive-docs.ts).\n` +
      `import type { DocSection } from '../docs';\n\n` +
      `export const sections: DocSection[] = ${JSON.stringify(sections, null, 2)};\n`,
  );
  written.push(list);
  writeFileSync(join(archiveDir, 'index.ts'), registry(archiveDir));
  return written;
}

/** src/lib/docs-archive/index.ts for the snapshots present in `dir`. */
export function registry(dir: string): string {
  const all = readdirSync(dir)
    .map((f) => f.replace(/\.ts$/, ''))
    .filter(isSeries)
    .sort((a, b) => b.localeCompare(a, 'en', { numeric: true }));
  const id = (s: string) => `v${s.replaceAll('.', '_')}`;
  return [
    '// Documentation snapshots of older minor versions: `<series>.ts` holds the',
    '// page list, the pages live under routes/docs/<series>/. Generated by',
    '// scripts/archive-docs.ts — do not edit.',
    "import type { DocSection } from '../docs';",
    ...all.map((s) => `import { sections as ${id(s)} } from './${s}';`),
    '',
    '/** Page lists of archived versions by series (`"0.1"`). */',
    ...(all.length
      ? [
          'export const archives: Record<string, DocSection[]> = {',
          ...all.map((s) => `  '${s}': ${id(s)},`),
          '};',
        ]
      : ['export const archives: Record<string, DocSection[]> = {};']),
    '',
  ].join('\n');
}

if (import.meta.main) {
  const series = process.argv[2];
  if (!series) {
    console.error('usage: bun scripts/archive-docs.ts <version, e.g. 0.2.1 (or a series, 0.1)>');
    process.exit(2);
  }
  const { sections } = await import('../src/lib/docs');
  const site = join(import.meta.dir, '..');
  const files = archiveDocs({
    series,
    routesDir: join(site, 'src/routes/docs'),
    archiveDir: join(site, 'src/lib/docs-archive'),
    sections,
  });
  console.log(`archived the docs as ${series}: ${files.length} files`);
  const { writeLlms } = await import('./llms');
  console.log(`wrote ${writeLlms().length} llms files`);
}
